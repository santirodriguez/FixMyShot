#!/usr/bin/env python3
"""No-network regressions for critical GAV coverage and generated-hash trust boundaries."""
import importlib.util
from pathlib import Path
import unittest
import xml.etree.ElementTree as ET

spec = importlib.util.spec_from_file_location('gradle_audit', Path(__file__).with_name('audit-gradle-candidates.py'))
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)
NS = 'https://schema.gradle.org/dependency-verification'


def fake_metadata():
    root = ET.Element(f'{{{NS}}}verification-metadata')
    config = ET.SubElement(root, f'{{{NS}}}configuration')
    ET.SubElement(config, f'{{{NS}}}verify-metadata').text = 'true'
    ET.SubElement(config, f'{{{NS}}}verify-signatures').text = 'false'
    comps = ET.SubElement(root, f'{{{NS}}}components')
    for group, name, version, ext, _ in audit.CRITICAL:
        component = ET.SubElement(comps, f'{{{NS}}}component', group=group, name=name, version=version)
        artifact = ET.SubElement(component, f'{{{NS}}}artifact', name=f'{name}-{version}{ext}')
        ET.SubElement(artifact, f'{{{NS}}}sha256', value='a'*64, origin='Generated by Gradle')
    return root


class TrustCaptureTests(unittest.TestCase):
    def test_generated_hashes_are_never_claimed_authenticated(self):
        report = audit.audit_metadata(ET.tostring(fake_metadata()))
        self.assertEqual(len(audit.CRITICAL), len(report['critical_candidates']))
        self.assertEqual(len(audit.CRITICAL), report['generated_origin_count'])
        self.assertFalse(any(x['publisher_sha_independently_verified'] for x in report['critical_candidates']))
        self.assertEqual(0, report['pgp_signature_count'])

    def test_missing_critical_artifact_fails_closed(self):
        root = fake_metadata()
        root.find(f'{{{NS}}}components').remove(list(root.find(f'{{{NS}}}components'))[0])
        with self.assertRaises(ValueError):
            audit.audit_metadata(ET.tostring(root))

    def test_duplicate_coordinates_fail_closed(self):
        root = fake_metadata()
        comps = root.find(f'{{{NS}}}components')
        first = list(comps)[0]
        comps.append(ET.fromstring(ET.tostring(first)))
        with self.assertRaises(ValueError):
            audit.audit_metadata(ET.tostring(root))

    def test_wrong_sha256_fails_closed(self):
        root = fake_metadata()
        root.find(f'.//{{{NS}}}sha256').set('value', 'f'*63)
        with self.assertRaises(ValueError):
            audit.audit_metadata(ET.tostring(root))

    def test_missing_verification_configuration_fails_closed(self):
        root = fake_metadata()
        root.remove(root.find(f'{{{NS}}}configuration'))
        with self.assertRaises(ValueError):
            audit.audit_metadata(ET.tostring(root))

    def test_metadata_too_large_fails_closed(self):
        with self.assertRaises(ValueError):
            audit.audit_metadata(b'x' * 3_000_001)

    def test_duplicate_artifact_fails_closed(self):
        root = fake_metadata()
        artifact = root.find(f'.//{{{NS}}}artifact')
        parent = root.find(f'.//{{{NS}}}component')
        parent.append(ET.fromstring(ET.tostring(artifact)))
        with self.assertRaises(ValueError):
            audit.audit_metadata(ET.tostring(root))


if __name__ == '__main__':
    unittest.main()
